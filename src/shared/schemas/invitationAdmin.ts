import { z } from 'zod';
import type { Tables, TablesInsert } from '@/shared/types/database.types';
import { isInvitationCode } from '@/shared/utils/code';

// Invitation data the admin edits (and CSV rows), with the same limits as the table.

export const SIDES = ['bride', 'groom', 'both'] as const;
export type Side = (typeof SIDES)[number];

export const SIDE_LABELS: Record<Side, string> = {
  bride: 'Novia',
  groom: 'Novio',
  both: 'Ambos',
};

const PHONE = /^[0-9+() -]{6,30}$/;

export const invitationInputSchema = z.object({
  displayName: z.string().trim().min(1, 'Escribe el nombre').max(120, 'Máximo 120 caracteres'),
  seats: z
    .number({ error: 'Indica los pases' })
    .int('Número entero')
    .min(1, 'Mínimo 1 pase')
    .max(20, 'Máximo 20 pases'),
  side: z.enum(SIDES, { error: 'Elige novia, novio o ambos' }),
  groupName: z.string().trim().max(60, 'Máximo 60 caracteres'),
  phone: z
    .string()
    .trim()
    .refine((v) => v === '' || PHONE.test(v), 'Teléfono no válido'),
  email: z
    .string()
    .trim()
    .max(254)
    .refine((v) => v === '' || z.email().safeParse(v).success, 'Correo no válido'),
  notes: z.string().trim().max(2000, 'Máximo 2000 caracteres'),
  code: z
    .string()
    .trim()
    .toLowerCase()
    .refine(
      (v) => v === '' || isInvitationCode(v),
      'Código de 4 caracteres, sin 0, 1, i, l ni o (vacío = automático)',
    ),
});

export type InvitationInput = z.infer<typeof invitationInputSchema>;
export type InvitationRow = Tables<'invitations'>;
export type AttendeeRow = Tables<'attendees'>;
export type InvitationWithAttendees = InvitationRow & { attendees: AttendeeRow[] };

export function emptyInvitationInput(): InvitationInput {
  return {
    displayName: '',
    seats: 1,
    side: 'both',
    groupName: '',
    phone: '',
    email: '',
    notes: '',
    code: '',
  };
}

export function invitationInputFromRow(row: InvitationRow): InvitationInput {
  return {
    displayName: row.display_name,
    seats: row.seats,
    side: row.side as Side,
    groupName: row.group_name ?? '',
    phone: row.phone ?? '',
    email: row.email ?? '',
    notes: row.notes ?? '',
    code: row.code,
  };
}

/** Columns to write. An empty code is generated by the database (trigger). */
export function invitationRowFromInput(input: InvitationInput): TablesInsert<'invitations'> {
  const orNull = (value: string) => value.trim() || null;
  return {
    display_name: input.displayName.trim(),
    seats: input.seats,
    side: input.side,
    group_name: orNull(input.groupName),
    phone: orNull(input.phone),
    email: orNull(input.email),
    notes: orNull(input.notes),
    // null lets the BEFORE INSERT trigger generate one.
    code: input.code ? input.code.toLowerCase() : (null as unknown as string),
  };
}

export type ResponseStatus = 'pending' | 'attending' | 'declined';

export function responseStatus(row: Pick<InvitationRow, 'attending'>): ResponseStatus {
  if (row.attending === null) return 'pending';
  return row.attending ? 'attending' : 'declined';
}
